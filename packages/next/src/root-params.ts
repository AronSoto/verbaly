import type { ResolvedConfig } from '@verbaly/compiler';
import { existsSync, readdirSync, readFileSync, type Dirent } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

// next/root-params is on by default from 16.3.0; 16.2 ships the same file behind a flag
const ROOT_PARAMS_SINCE = [16, 3] as const;
const LAYOUT_FILE = /^layout\.[cm]?[jt]sx?$/;
const DYNAMIC_SEGMENT = /^\[([A-Za-z_$][\w$]*)\]$/;
// how far a root layout can sit under app/: route groups and a static prefix or two
const MAX_DEPTH = 4;

// the project's own next, found by walking node_modules up from the root, never NODE_PATH's
export function resolveFromNext(root: string, file: string): string | undefined {
  for (let dir = root; ; dir = dirname(dir)) {
    if (existsSync(join(dir, 'node_modules', 'next', 'package.json'))) {
      const path = join(dir, 'node_modules', file);
      return existsSync(path) ? path : undefined;
    }
    if (dirname(dir) === dir) break;
  }
  // Yarn PnP has no node_modules, and its resolver finds the project's own next
  if (!process.versions.pnp) return undefined;
  try {
    return createRequire(join(root, 'package.json')).resolve(file);
  } catch {
    return undefined;
  }
}

// the installed next cannot change under a running dev server, and the watcher asks on every save
const supported = new Map<string, boolean>();

function hasRootParams(root: string): boolean {
  let answer = supported.get(root);
  if (answer === undefined) {
    answer = readRootParamsSupport(root);
    supported.set(root, answer);
  }
  return answer;
}

function readRootParamsSupport(root: string): boolean {
  const manifest = resolveFromNext(root, 'next/package.json');
  if (!manifest) return false;
  try {
    const version = String(JSON.parse(readFileSync(manifest, 'utf8')).version);
    const [release = '', prerelease] = version.split('-');
    const [major = 0, minor = 0, patch = 0] = release.split('.').map(Number);
    const [sinceMajor, sinceMinor] = ROOT_PARAMS_SINCE;
    // a 16.3.0 canary predates the release that turned the module on by default
    if (prerelease !== undefined && major === sinceMajor && minor === sinceMinor && patch === 0) {
      return false;
    }
    return major > sinceMajor || (major === sinceMajor && minor >= sinceMinor);
  } catch {
    return false;
  }
}

// Next reads app/ first and src/app only without it; one dynamic segment above every root layout
export function findRootParam(root: string): string | undefined {
  const app = [join(root, 'app'), join(root, 'src', 'app')].find((dir) => existsSync(dir));
  if (!app) return undefined;
  const found = new Set<string | undefined>();

  const walk = (dir: string, params: string[], depth: number): void => {
    let entries: Dirent[];
    try {
      entries = readdirSync(dir, { withFileTypes: true });
    } catch {
      return;
    }
    if (entries.some((entry) => entry.isFile() && LAYOUT_FILE.test(entry.name))) {
      // a root layout with no segment, or with two, cannot say which one holds the locale
      found.add(params.length === 1 ? params[0] : undefined);
      return;
    }
    if (depth === MAX_DEPTH) return;
    for (const entry of entries) {
      if (!entry.isDirectory() || /^[_@.]/.test(entry.name) || entry.name === 'node_modules')
        continue;
      const segment = DYNAMIC_SEGMENT.exec(entry.name)?.[1];
      walk(join(dir, entry.name), segment ? [...params, segment] : params, depth + 1);
    }
  };

  walk(app, [], 0);
  const [only] = found;
  return found.size === 1 ? only : undefined;
}

// what server.ts reads when no setRequestLocale reached the segment: a page, 'use cache', metadata
export function generateServerModule(cfg: ResolvedConfig): string {
  const param =
    cfg.routing !== 'no-prefix' && hasRootParams(cfg.root) ? findRootParam(cfg.root) : undefined;
  if (!param) {
    return '// generated by @verbaly/next: no root segment to read, setRequestLocale declares it\nexport const rootLocale = undefined;\n';
  }
  return (
    `// generated by @verbaly/next: the [${param}] segment of the root layout, through next/root-params\n` +
    `import { ${param} as segment } from 'next/root-params';\n` +
    'export const rootLocale = segment;\n'
  );
}
